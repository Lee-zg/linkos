import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(`${process.cwd()}/apps/web/package.json`);
const { chromium, expect } = require('@playwright/test');
const base = 'http://127.0.0.1:15173';
const out = `${process.cwd()}/spark-output/audit/evidence`;
const browser = await chromium.launch({ headless: true });
const evidence = { generated_at: new Date().toISOString(), environment: { browser: browser.version(), base, isolatedGateway: true, runnerStarted: false }, checks: [], consoleErrors: [] };
const record = (id, data) => { evidence.checks.push({ id, ...data }); console.log(JSON.stringify({ id, ...data })); };
const openApp = async (page, name) => { await page.getByRole('button', { name, exact: true }).last().click(); const dialog = page.getByRole('dialog', { name, exact: true }); await expect(dialog).toBeVisible(); await expect(dialog).toHaveCSS('opacity', '1'); return dialog; };
const closeApp = async (page, name) => { await page.getByRole('button', { name: `关闭 ${name}`, exact: true }).click(); await expect(page.getByRole('dialog', { name, exact: true })).toHaveCount(0); };
async function login(context, name, admin = false) {
  const page = await context.newPage();
  page.on('pageerror', error => evidence.consoleErrors.push(error.message));
  await page.goto(base);
  await page.getByRole('textbox', { name: '显示名', exact: true }).fill(name);
  if (admin) await page.getByRole('textbox', { name: '口令（可选）', exact: true }).fill('audit-local-only-20260923');
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/v1/sessions') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '登录进入', exact: true }).click();
  const response = await responsePromise;
  assert.equal(response.status(), 201);
  const session = await response.json();
  await expect(page.getByRole('status', { name: '已连接工作区', exact: true })).toBeVisible();
  return { page, token: session.accessToken, role: session.role };
}
