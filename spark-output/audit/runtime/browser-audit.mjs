  record('settings', { notificationBeforeReopen: before, notificationAfterReopen: after, diagnosticDownloadEvents: downloadCount });
  await closeApp(page, '设置');

  let files = await openApp(page, '文件');
  const filename = 'audit-shared-file.txt';
